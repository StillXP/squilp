import { existsSync, globSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { argv } from 'node:process';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { checkModes, colorModes } from './modes.js';
import { checkOverrides } from './overrides.js';
import { cssConfig, nativeConfig, tailwindConfig } from './style-dictionary.config.js';

const posix = (path) => path.replaceAll('\\', '/');
const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

function merge(into, from) {
  for (const [key, value] of Object.entries(from)) {
    const both = into[key] && typeof into[key] === 'object' && value && typeof value === 'object';
    into[key] = both ? merge({ ...into[key] }, value) : value;
  }
  return into;
}

async function load(config, files) {
  const dictionary = new StyleDictionary({ ...config, ...files }, { init: false });
  await dictionary.init();
  return dictionary;
}

async function format(config, files) {
  const dictionary = await load(config, files);
  const [platform] = Object.keys(config.platforms);
  const [{ output }] = await dictionary.formatPlatform(platform);
  return output.trim();
}

// color.background.accent.hover becomes backgroundAccentHover.
function nativeName({ path }) {
  const words = path.slice(1).filter((part) => part !== '$root').flatMap((part) => part.split('-'));
  return words.map((word, index) => (index === 0 ? word : word[0].toUpperCase() + word.slice(1))).join('');
}

// Shared values are the web values. A platform file holds the values that differ
// on iOS or Android, and a color mode file holds every semantic color.
export async function buildTokens(src, dist) {
  const at = (...parts) => posix(join(src, ...parts));
  const shared = globSync('**/*.tokens.json', { cwd: src })
    .map(posix)
    .filter((file) => !/^(platform|color-mode)\//.test(file))
    .sort()
    .map((file) => at(file));
  const sharedTokens = shared.map(readJson).reduce(merge, {});

  const modeFiles = Object.fromEntries(
    globSync('color-mode/*.tokens.json', { cwd: src }).map((file) => [basename(file, '.tokens.json'), at(file)]),
  );
  const hasModes = Object.keys(modeFiles).length > 0;
  if (hasModes) {
    checkModes(sharedTokens, Object.fromEntries(Object.entries(modeFiles).map(([mode, file]) => [mode, readJson(file)])));
  }

  // Style Dictionary lets source override include. Two sources would be a collision.
  const withShared = (file) => ({ include: shared, source: [file] });
  const css = [await format(cssConfig(':root', 'squilp/built'), { source: shared })];
  const colors = {};
  for (const mode of hasModes ? colorModes : []) {
    const selector = `[data-color-mode='${mode}']`;
    css.push(await format(cssConfig(mode === colorModes[0] ? `:root,\n${selector}` : selector, 'squilp/mode'), withShared(modeFiles[mode])));
    const { allTokens } = await (await load(nativeConfig, withShared(modeFiles[mode]))).getPlatformTokens('reactNative');
    colors[mode] = Object.fromEntries(allTokens.filter((token) => token.isSource).map((token) => [nativeName(token), token.$value]));
  }

  const tailwind = await format(tailwindConfig, hasModes ? withShared(modeFiles[colorModes[0]]) : { source: shared });

  const native = {};
  for (const platform of ['ios', 'android']) {
    const file = at('platform', `${platform}.tokens.json`);
    const differs = existsSync(file);
    if (differs) checkOverrides(platform, sharedTokens, readJson(file));
    const tokens = JSON.parse(await format(nativeConfig, differs ? withShared(file) : { source: shared }));
    native[platform] = hasModes ? { ...tokens, color: colors } : tokens;
  }

  const write = (file, content) => {
    mkdirSync(join(dist, file, '..'), { recursive: true });
    writeFileSync(join(dist, file), `${content}\n`);
  };
  write('css/tokens.css', ['/* Generated by Style Dictionary. */', ...css].join('\n\n'));
  write('tailwind.css', tailwind);
  write('react-native/tokens.js', `export default ${JSON.stringify(native, null, 2)};`);
}

if (argv[1] === fileURLToPath(import.meta.url)) {
  const here = fileURLToPath(new URL('.', import.meta.url));
  await buildTokens(join(here, 'src'), join(here, 'dist'));
}
